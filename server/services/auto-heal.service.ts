// ── Types ──────────────────────────────────────────────────────────────────

export interface HealRule {
  id: string;
  name: string;
  condition: (checks: HealthCheckItem[], result: HealthCheckResult) => boolean;
  action: HealAction;
  cooldownMs: number;
  maxExecutions: number;
  requiresConfirmation: boolean;
  enabled: boolean;
}

export type HealAction =
  | { type: 'send_alert'; severity: string; message: string }
  | { type: 'log_only'; message: string };

// ── Execution Tracking ─────────────────────────────────────────────────────

const executionLog = new Map<string, { count: number; lastAt: number; windowStart: number }>();
const COOLDOWN_WINDOW_MS = 3600_000; // 1 hour rolling window

function isInCooldown(rule: HealRule): boolean {
  const log = executionLog.get(rule.id);
  if (!log) return false;
  return Date.now() - log.lastAt < rule.cooldownMs;
}

function exceedsRateLimit(rule: HealRule): boolean {
  const log = executionLog.get(rule.id);
  if (!log) return false;
  // Reset window if expired
  if (Date.now() - log.windowStart > COOLDOWN_WINDOW_MS) {
    executionLog.set(rule.id, { count: 0, lastAt: log.lastAt, windowStart: Date.now() });
    return false;
  }
  return log.count >= rule.maxExecutions;
}

function recordExecution(ruleId: string): void {
  const log = executionLog.get(ruleId);
  const now = Date.now();
  if (!log || now - log.windowStart > COOLDOWN_WINDOW_MS) {
    executionLog.set(ruleId, { count: 1, lastAt: now, windowStart: now });
  } else {
    log.count++;
    log.lastAt = now;
  }
}

