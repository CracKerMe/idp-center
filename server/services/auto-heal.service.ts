// ── Execute Heal Action ────────────────────────────────────────────────────

async function executeAction(rule: HealRule, result: HealthCheckResult): Promise<void> {
  const id = crypto.randomUUID();

  try {
    switch (rule.action.type) {
      case 'send_alert':
        await createAlert({
          tenantId: 'system',
          severity: rule.action.severity as any,
          category: 'system',
          title: rule.name,
          description: rule.action.message,
          metadata: { ruleId: rule.id, healthScore: result.score },
        });
        break;

      case 'log_only':
        logger.info(`Auto-heal [${rule.id}]: ${rule.action.message}`);
        break;
    }

    // Log success
    await db.insert(autoHealLog).values({
      id,
      ruleId: rule.id,
      ruleName: rule.name,
      actionType: rule.action.type,
      actionParams: JSON.stringify(rule.action),
      status: 'success',
      executedBy: 'system',
    });

    recordExecution(rule.id);
    logger.info(`Auto-heal executed: ${rule.name}`, { ruleId: rule.id });

  } catch (err: any) {
    logger.error(`Auto-heal failed: ${rule.name}`, { error: err.message });
    await db.insert(autoHealLog).values({
      id,
      ruleId: rule.id,
      ruleName: rule.name,
      actionType: rule.action.type,
      actionParams: JSON.stringify(rule.action),
      status: 'failed',
      error: err.message,
      executedBy: 'system',
    });
  }
}

// ── Main Tick ──────────────────────────────────────────────────────────────

/** Main auto-heal loop — called by scheduler every AUTO_HEAL_TICK_INTERVAL_MS */
export async function autoHealTick(): Promise<void> {
  // Check if auto-heal is enabled via the feature toggle system
  if (!isEnabled('autoHeal')) {
    logger.debug('Auto-heal is disabled via the autoHeal feature flag');
    return;
  }

  try {
    const result = await runHealthCheck();

    // Persist health check result (fixes: scheduler runs weren't being recorded)
    await persistHealthCheck(result);

    for (const rule of HEAL_RULES) {
      if (!rule.enabled) continue;
      if (!rule.condition(result.checks, result)) continue;
      if (isInCooldown(rule)) continue;
      if (exceedsRateLimit(rule)) continue;

      await executeAction(rule, result);
    }
  } catch (err: any) {
    logger.error(`Auto-heal tick failed: ${err.message}`);
  }
}

/** Get auto-heal execution log */
export async function getAutoHealLog(hours: number = 24): Promise<Array<{
  ruleId: string;
  ruleName: string;
  actionType: string;
  status: string;
  error?: string;
  executedAt: Date;
}>> {
  const since = new Date(Date.now() - hours * 3600_000);
  const rows = await db.select()
    .from(autoHealLog)
    .where(gte(autoHealLog.executedAt, since))
    .orderBy(desc(autoHealLog.executedAt))
    .limit(100);

  return rows.map(r => ({
    ruleId: r.ruleId,
    ruleName: r.ruleName,
    actionType: r.actionType,
    status: r.status,
    error: r.error ?? undefined,
    executedAt: r.executedAt!,
  }));
}

/** Get list of all heal rules with their enabled status */
export function getHealRules(): Array<{ id: string; name: string; enabled: boolean; requiresConfirmation: boolean }> {
  return HEAL_RULES.map(r => ({
    id: r.id,
    name: r.name,
    enabled: r.enabled,
    requiresConfirmation: r.requiresConfirmation,
  }));
}

/** Update a heal rule's enabled status */
export function updateHealRule(ruleId: string, enabled: boolean): boolean {
  const rule = HEAL_RULES.find(r => r.id === ruleId);
  if (!rule) return false;
  rule.enabled = enabled;
  return true;
}
